import { getEnv } from "~/context/env";
import { donationOptionsFromEnv } from "~/shared/support/donations";
import { renderQrSvg } from "~/support/qr.server";
import { HeartIcon } from "~/ui/icons";
import { PageIntro } from "~/ui/page-layouts";

import type { Route } from "./+types/support";

/**
 * Optional, anonymous donation page (spec §1.2, ADR-0007).
 *
 * It requires no Account, session, or personal data; creates no record in D1
 * or any operational store; and is server-rendered from operator-published
 * static addresses in Worker vars. QR codes are generated locally from the
 * exact displayed address, so the page embeds no third-party script, widget,
 * tracker, or analytics and makes no external request.
 */
export async function loader({ context }: Route.LoaderArgs) {
  const options = donationOptionsFromEnv(getEnv(context));
  return {
    options: await Promise.all(
      options.map(async (option) => ({ ...option, qrSvg: await renderQrSvg(option.address) })),
    ),
  };
}

